export const LOCALES = ["en", "ar"] as const;
export type Locale = (typeof LOCALES)[number];

export function isLocale(value: string | null | undefined): value is Locale {
  return (LOCALES as readonly string[]).includes(value ?? "");
}

export const NUMERAL_STYLES = ["latin", "arabic"] as const;
export type NumeralStyle = (typeof NUMERAL_STYLES)[number];

export function isNumeralStyle(value: string | null | undefined): value is NumeralStyle {
  return (NUMERAL_STYLES as readonly string[]).includes(value ?? "");
}

export function localePath(locale: Locale, path: string): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (locale === "ar") {
    return clean === "/" ? "/ar" : `/ar${clean}`;
  }
  return clean === "/ar" ? "/" : clean.replace(/^\/ar(?=\/|$)/, "") || "/";
}

